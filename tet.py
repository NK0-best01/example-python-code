myInput = int(input()) 
# รับค่าเข้าเป็นจำนวนเต็ม
myInput = int(myInput+1)
# เพิ่มค่า myInput ขึ้น 1 
for x in range(1,myInput):
    # วนลูป for เพื่อทำซ้ำตามจำนวนที่ป้อนเข้ามา นับจาก 1 - myInput
    y=0
    # กำหนดตัวแปร y เป็น 0 
    while y!=x:
        # วนลูปทำซ้ำจนกว่า y จะเท่ากับ x
        print("*",end='')
        # พิมพ์เครื่องหมาย * ไม่ขึ้นบรรทัดใหม่
        y+=1
        # เพิ่ม y ขึ้น 1
        if y==x:
            # เช็คว่า y เท่ากับ x เปล่า
            break
        # ถ้า y เท่ากับ x ให้หยุดการทำงานของลูป 
    print()
    # พิมพ์ขึ้นบรรทัดใหม่
# แล้ววนลูป for จะทำซ้ำจนกว่าจะครบจำนวนที่ป้อนเข้ามา